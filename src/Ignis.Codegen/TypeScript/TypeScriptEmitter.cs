using System.Text;

using Hl7.Fhir.Model;
using Hl7.Fhir.Specification.Source;

namespace Ignis.Codegen.TypeScript;

/// <summary>Collects definitions and the types they reference, then renders types.ts, extensions.ts and index.ts.</summary>
public sealed class TypeScriptEmitter(IAsyncResourceResolver resolver)
{
    private const string CoreCanonicalBase = "http://hl7.org/fhir/StructureDefinition/";
    private const string FhirPathTypePrefix = "http://hl7.org/fhirpath/";
    private const string FhirModelImportPath = "../../model";
    private const string GeneratedFileHeader = "// Generated by Ignis.Codegen from FHIR StructureDefinitions. Do not edit.\n\n";

    private readonly Queue<string> _pendingCanonicals = new();
    private readonly HashSet<string> _seenCanonicals = new(StringComparer.Ordinal);
    private readonly SortedDictionary<string, string> _coreTypeSources = new(StringComparer.Ordinal);
    private readonly SortedDictionary<string, string> _extensionSources = new(StringComparer.Ordinal);
    private readonly SortedSet<string> _typesImportedByExtensions = new(StringComparer.Ordinal) { "Extension" };
    private readonly SortedSet<string> _concreteResourceTypeNames = new(StringComparer.Ordinal);

    public int TypeCount => _coreTypeSources.Count;

    public int ExtensionCount => _extensionSources.Count;

    /// <summary>Adds a definition by core type name or canonical, plus every type it references.</summary>
    public async Task AddDefinitionAsync(string typeNameOrCanonical)
    {
        Enqueue(typeNameOrCanonical.Contains('/') ? typeNameOrCanonical : CoreCanonicalBase + typeNameOrCanonical);
        while (_pendingCanonicals.TryDequeue(out var canonical))
            await RenderDefinitionAsync(canonical);
    }

    public IEnumerable<(string Name, string Content)> RenderFiles(string? fhirVersion)
    {
        yield return ("types.ts", RenderTypesFile());
        if (_extensionSources.Count > 0) yield return ("extensions.ts", RenderExtensionsFile());
        yield return ("index.ts", RenderIndexFile(fhirVersion));
    }

    private async Task RenderDefinitionAsync(string canonical)
    {
        var definition = await ResolveDefinitionWithSnapshotAsync(canonical);
        var typeName = definition.Type ?? throw new InvalidOperationException($"no type: {canonical}");

        // Checked before the primitive kind: some packages mislabel extensions (no-basis-middlename says primitive-type).
        if (definition.IsExtensionDefinition())
        {
            var definitionName = definition.Name ?? typeName;
            _extensionSources[definitionName] = ExtensionRenderer.Render(definition, definitionName, MapExtensionValueType);
            return;
        }

        if (definition.IsPrimitiveType()) return;
        if (definition.IsProfile()) throw new NotSupportedException($"profiles are not generated yet: {canonical}");

        Enqueue(CoreCanonicalBase + "Element");
        if (definition.IsConcreteResource()) _concreteResourceTypeNames.Add(typeName);
        _coreTypeSources[typeName] = CoreTypeRenderer.Render(definition, typeName, MapType);
    }

    private async Task<StructureDefinition> ResolveDefinitionWithSnapshotAsync(string canonical)
    {
        var resolution = await resolver.TryResolveByCanonicalUriAsync(canonical);
        if (resolution is not { Success: true, Value: StructureDefinition definition })
            throw new InvalidOperationException($"not found: {canonical}" + (resolution.Error is { } error ? $" ({error.Message})" : ""));
        if (!definition.HasSnapshot) throw new InvalidOperationException($"no snapshot: {canonical}");
        return definition;
    }

    private string MapType(string typeCode)
    {
        if (FhirPrimitiveTypes.TryGetTypeScriptType(typeCode, out var primitiveType)) return primitiveType;
        if (typeCode.StartsWith(FhirPathTypePrefix, StringComparison.Ordinal)) return "string";

        Enqueue(CoreCanonicalBase + typeCode);
        return typeCode;
    }

    // extensions.ts imports the generated types its values use from types.ts.
    private string MapExtensionValueType(string typeCode)
    {
        var typeScriptType = MapType(typeCode);
        if (typeScriptType == typeCode && !FhirPrimitiveTypes.IsPrimitive(typeCode)) _typesImportedByExtensions.Add(typeScriptType);
        return typeScriptType;
    }

    private void Enqueue(string canonical)
    {
        if (_seenCanonicals.Add(canonical)) _pendingCanonicals.Enqueue(canonical);
    }

    private string RenderTypesFile()
    {
        var fileContent = new StringBuilder(GeneratedFileHeader);
        foreach (var typeSource in _coreTypeSources.Values)
            fileContent.Append(typeSource).Append('\n');
        return fileContent.ToString();
    }

    private string RenderExtensionsFile()
    {
        var fileContent = new StringBuilder(GeneratedFileHeader);
        fileContent.Append("import type { ").Append(string.Join(", ", _typesImportedByExtensions)).Append(" } from \"./types\";\n");
        fileContent.Append("import type { ExtensionDefinition } from \"").Append(FhirModelImportPath).Append("\";\n\n");
        foreach (var typeSource in _extensionSources.Values)
            fileContent.Append(typeSource).Append('\n');
        return fileContent.ToString();
    }

    private string RenderIndexFile(string? fhirVersion)
    {
        var fileContent = new StringBuilder(GeneratedFileHeader);
        fileContent.Append("export type * from \"./types\";\n");
        if (_extensionSources.Count > 0) fileContent.Append("export * from \"./extensions\";\n");

        if (fhirVersion is not null)
        {
            fileContent.Append("\n/** The FHIR version these types were generated from. */\n");
            fileContent.Append("export const fhirVersion = ").Append(TypeScriptRenderer.StringLiteral(fhirVersion)).Append(";\n");
        }

        if (_concreteResourceTypeNames.Count > 0)
        {
            fileContent.Append("\nimport type { ").Append(string.Join(", ", _concreteResourceTypeNames)).Append(" } from \"./types\";\n\n");
            fileContent.Append("/** Every concrete resource; narrows on `resourceType`. */\n");
            fileContent.Append("export type AnyResource =\n  | ").Append(string.Join("\n  | ", _concreteResourceTypeNames)).Append(";\n\n");
            fileContent.Append("export type ResourceType = AnyResource[\"resourceType\"];\n\n");
            fileContent.Append("/** Every concrete resource type name, for runtime checks. */\n");
            fileContent.Append("export const resourceTypes = [\n  ")
                .Append(string.Join(",\n  ", _concreteResourceTypeNames.Select(TypeScriptRenderer.StringLiteral)))
                .Append(",\n] as const satisfies readonly ResourceType[];\n");
        }

        return fileContent.ToString();
    }
}
